def test_good_design_has_no_errors(base_req: RequirementsInput):
    """A standard compliant design generated by the pipeline must have zero error-severity issues."""
    design = run_pipeline(base_req, variant="balanced")
    error_issues = [i for i in design.validation if i.severity == "error"]
    assert len(error_issues) == 0, f"Unexpected validation errors: {error_issues}"


def test_rule_addr_overlap(base_req: RequirementsInput):
    design = run_pipeline(base_req, variant="balanced")
    # Deliberately modify second subnet to overlap with first
    bad_subnets = list(design.subnets)
    bad_subnets[1] = bad_subnets[1].model_copy(
        update={"network": bad_subnets[0].network, "prefix": bad_subnets[0].prefix}
    )
    bad_design = design.model_copy(update={"subnets": bad_subnets})

    issues = validate_design(bad_design, base_req)
    assert any(i.code == "ADDR_OVERLAP" and i.severity == "error" for i in issues)


