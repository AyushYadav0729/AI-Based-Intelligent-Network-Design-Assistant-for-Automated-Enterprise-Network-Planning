def test_rule_security_guest_not_isolated(base_req: RequirementsInput):
    design = run_pipeline(base_req, variant="balanced")
    sec = dict(design.security)
    matrix = dict(sec.get("acl_matrix", {}))
    # Deliberately allow guest to reach internal SERVERS
    if "GUEST" in matrix:
        matrix["GUEST"] = dict(matrix["GUEST"])
        matrix["GUEST"]["SERVERS"] = "permit"
    sec["acl_matrix"] = matrix
    bad_design = design.model_copy(update={"security": sec})

    issues = validate_design(bad_design, base_req)
    assert any(i.code == "SECURITY_GUEST_NOT_ISOLATED" and i.severity == "error" for i in issues)


